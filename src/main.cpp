void updateMotionMetrics() {
  gAccelMag = sqrtf(gAccelXG * gAccelXG + gAccelYG * gAccelYG + gAccelZG * gAccelZG);
  gDeltaAccel = fabsf(gAccelMag - gLastAccelMag);
  gLastAccelMag = gAccelMag;

  const float motionAccel = fabsf(gAccelMag - 1.0f);
  gMotionRaw = motionAccel * 0.6f + gDeltaAccel * 2.5f;
  gMotionIntensity = gMotionIntensity * (1.0f - kMotionSmoothingAlpha) +
                     gMotionRaw * kMotionSmoothingAlpha;
  gMotionNorm = clampFloat(gMotionIntensity / kMotionNormalizeG, 0.0f, 1.0f);
}

void updateImu() {
  if (!gMpuConnected) {
    gAccelXG = 0.0f;
    gAccelYG = 0.0f;
    gAccelZG = 1.0f;
    gSmoothedAccelXG += (gAccelXG - gSmoothedAccelXG) * kAccelSmoothingAlpha;
    gMotionRaw = 0.0f;
    gDeltaAccel = 0.0f;
    gAccelMag = 1.0f;
    gMotionIntensity = gMotionIntensity * (1.0f - kMotionSmoothingAlpha);
    gMotionNorm = clampFloat(gMotionIntensity / kMotionNormalizeG, 0.0f, 1.0f);
    return;
  }

  if (gUseRawMpu) {
    uint8_t raw[6] = {};
    if (!readI2cBytes(gMpuAddress, 0x3B, raw, sizeof(raw))) {
      gMpuConnected = false;
      gMpuAddress = 0;
      gUseRawMpu = false;
      Serial.println("ERROR: lectura raw MPU fallo. Sample usa velocidad fija.");
      return;
    }

    const int16_t accelXRaw = static_cast<int16_t>((raw[0] << 8) | raw[1]);
    const int16_t accelYRaw = static_cast<int16_t>((raw[2] << 8) | raw[3]);
    const int16_t accelZRaw = static_cast<int16_t>((raw[4] << 8) | raw[5]);
    gAccelXG = static_cast<float>(accelXRaw) / 16384.0f;
    gAccelYG = static_cast<float>(accelYRaw) / 16384.0f;
    gAccelZG = static_cast<float>(accelZRaw) / 16384.0f;
  } else {
    sensors_event_t accel;
    sensors_event_t gyro;
    sensors_event_t temp;
    if (!mpu.getEvent(&accel, &gyro, &temp)) {
      gMpuConnected = false;
      gMpuAddress = 0;
      gUseRawMpu = false;
      Serial.println("ERROR: lectura MPU6050 fallo. Sample usa velocidad fija.");
      return;
    }

    gAccelXG = accel.acceleration.x / SENSORS_GRAVITY_STANDARD;
    gAccelYG = accel.acceleration.y / SENSORS_GRAVITY_STANDARD;
    gAccelZG = accel.acceleration.z / SENSORS_GRAVITY_STANDARD;
  }

  gSmoothedAccelXG += (gAccelXG - gSmoothedAccelXG) * kAccelSmoothingAlpha;
  updateMotionMetrics();
}

float readSampleInterpolated(float position) {
  const size_t indexA = static_cast<size_t>(position);
  const size_t indexB = min(indexA + 1, kEmbeddedSampleLength - 1);
  const float fraction = position - static_cast<float>(indexA);
  const float a = static_cast<float>(kEmbeddedSample[indexA]);
  const float b = static_cast<float>(kEmbeddedSample[indexB]);
  return a + (b - a) * fraction;
}

void triggerChirp(uint32_t now) {
  SampleVoice* voice = nullptr;
  for (SampleVoice& candidate : gVoices) {
    if (!candidate.active) {
      voice = &candidate;
      break;
    }
  }

  if (voice == nullptr) {
    voice = &gVoices[0];
  }

  gQuietState = gMotionIntensity < kQuietThreshold;
  gTargetPitch = mapMotionToPitch(gMotionIntensity);
  gSmoothedPitch += (gTargetPitch - gSmoothedPitch) * kPitchSmoothingAlpha;

  voice->active = true;
  voice->position = 0.0f;
  voice->pitch = gSmoothedPitch;

  gFlashLevel = 1.0f;
  gLastChirpTriggered = true;

  const float targetInterval = mapMotionToIntervalMs(gMotionIntensity);
  gChirpIntervalMs += (targetInterval - gChirpIntervalMs) * kIntervalSmoothingAlpha;
  gNextChirpMs = now + static_cast<uint32_t>(gChirpIntervalMs);
}

void updateChirpScheduler(uint32_t now) {
  gQuietState = gMotionIntensity < kQuietThreshold;
  gSmoothedPitch += (mapMotionToPitch(gMotionIntensity) - gSmoothedPitch) * kPitchSmoothingAlpha;

  if (gNextChirpMs == 0 || now >= gNextChirpMs) {
    triggerChirp(now);
  }
}

void updateNeoPixel(uint32_t now) {
  const uint32_t elapsedMs = now - gLastLedUpdateMs;
  gLastLedUpdateMs = now;

  if (elapsedMs > 0 && gFlashLevel > 0.0f) {
    gFlashLevel = clampFloat(gFlashLevel - static_cast<float>(elapsedMs) * kFlashDecayPerMs, 0.0f, 1.0f);
  }

  const uint8_t red = static_cast<uint8_t>(255.0f * gFlashLevel);
  const uint8_t green = static_cast<uint8_t>(120.0f * gFlashLevel);
  const uint8_t blue = static_cast<uint8_t>(20.0f * gFlashLevel);
  const uint32_t color = strip.Color(red, green, blue);

  for (uint16_t i = 0; i < kNeoPixelCount; ++i) {
    strip.setPixelColor(i, color);
  }
  strip.show();
}

void writeAudioBuffer() {
  for (size_t i = 0; i < kFramesPerBuffer; ++i) {
    float mixedSample = 0.0f;
    for (SampleVoice& voice : gVoices) {
      if (!voice.active) {
        continue;
      }

      mixedSample += readSampleInterpolated(voice.position);
      voice.position += voice.pitch;
      if (voice.position >= static_cast<float>(kEmbeddedSampleLength - 1)) {
        voice.active = false;
      }
    }

    const int16_t pcm = clampToInt16(mixedSample * SAMPLE_GAIN);

    gAudioBuffer[i * 2] = pcm;
    gAudioBuffer[i * 2 + 1] = pcm;
  }

  size_t bytesWritten = 0;
  i2s_write(kI2sPort, gAudioBuffer, sizeof(gAudioBuffer), &bytesWritten, portMAX_DELAY);
}

