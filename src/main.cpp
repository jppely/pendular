float clampFloat(float value, float minValue, float maxValue) {
  if (value < minValue) return minValue;
  if (value > maxValue) return maxValue;
  return value;
}

int16_t clampToInt16(float value) {
  if (value > 32767.0f) return 32767;
  if (value < -32768.0f) return -32768;
  return static_cast<int16_t>(value);
}

float randomFloat(float minValue, float maxValue) {
  return minValue + (maxValue - minValue) * (static_cast<float>(random(0, 10001)) / 10000.0f);
}

float mapMotionToPitch(float motion) {
  if (motion < kQuietThreshold) {
    return randomFloat(0.95f, 1.08f);
  }

  const float motionCurve = gMotionNorm * gMotionNorm;
  const float basePitch = 1.00f + motionCurve * 0.04f;
  const float microVariation = randomFloat(-0.01f, 0.01f);
  return clampFloat(basePitch + microVariation, 0.99f, 1.05f);
}

float mapMotionToIntervalMs(float motion) {
  if (motion < kQuietThreshold) {
    return static_cast<float>(random(kQuietMinIntervalMs, kQuietMaxIntervalMs + 1));
  }

  const float motionCurve = gMotionNorm * gMotionNorm;
  return static_cast<float>(kMotionMaxIntervalMs) -
         motionCurve * static_cast<float>(kMotionMaxIntervalMs - kMotionMinIntervalMs);
}

bool i2cAddressResponds(uint8_t address) {
  Wire.beginTransmission(address);
  return Wire.endTransmission() == 0;
}

bool readI2cBytes(uint8_t address, uint8_t reg, uint8_t* buffer, size_t len) {
  Wire.beginTransmission(address);
  Wire.write(reg);
  if (Wire.endTransmission(false) != 0) return false;

  const uint8_t readCount = Wire.requestFrom(address, static_cast<uint8_t>(len));
  if (readCount != len) return false;

  for (size_t i = 0; i < len; ++i) {
    buffer[i] = Wire.read();
  }
  return true;
}

bool readI2cRegister(uint8_t address, uint8_t reg, uint8_t& value) {
  return readI2cBytes(address, reg, &value, 1);
}

bool writeI2cRegister(uint8_t address, uint8_t reg, uint8_t value) {
  Wire.beginTransmission(address);
  Wire.write(reg);
  Wire.write(value);
  return Wire.endTransmission() == 0;
}

void scanI2cBus() {
  Serial.print("I2C scan SDA=");
  Serial.print(kI2cSdaPin);
  Serial.print(" SCL=");
  Serial.print(kI2cSclPin);
  Serial.print(" found:");

  bool foundAny = false;
  for (uint8_t address = 1; address < 127; ++address) {
    if (i2cAddressResponds(address)) {
      Serial.print(" 0x");
      if (address < 16) Serial.print("0");
      Serial.print(address, HEX);
      foundAny = true;
    }
  }

  if (!foundAny) Serial.print(" none");
  Serial.println();
}

