bool initMpu() {
  gMpuConnected = false;
  gMpuAddress = 0;
  gUseRawMpu = false;

  if (mpu.begin(0x68, &Wire)) {
    gMpuConnected = true;
    gMpuAddress = 0x68;
  } else if (mpu.begin(0x69, &Wire)) {
    gMpuConnected = true;
    gMpuAddress = 0x69;
  }

  if (gMpuConnected) {
    mpu.setAccelerometerRange(MPU6050_RANGE_2_G);
    mpu.setGyroRange(MPU6050_RANGE_250_DEG);
    mpu.setFilterBandwidth(MPU6050_BAND_21_HZ);
    Serial.print("MPU6050 conectado por Adafruit en 0x");
    Serial.println(gMpuAddress, HEX);
    return true;
  }

  const uint8_t candidates[] = {0x68, 0x69};
  for (uint8_t address : candidates) {
    if (!i2cAddressResponds(address)) continue;

    uint8_t whoAmI = 0;
    readI2cRegister(address, 0x75, whoAmI);
    Serial.print("MPU-like en 0x");
    Serial.print(address, HEX);
    Serial.print(" WHO_AM_I=0x");
    if (whoAmI < 16) Serial.print("0");
    Serial.println(whoAmI, HEX);

    if (!writeI2cRegister(address, 0x6B, 0x00)) continue;
    writeI2cRegister(address, 0x1C, 0x00);  // accel +/-2g
    writeI2cRegister(address, 0x1A, 0x04);  // low-pass filter near 21 Hz

    gMpuConnected = true;
    gMpuAddress = address;
    gUseRawMpu = true;
    Serial.println("Usando lectura raw compatible MPU por registros.");
    return true;
  }

  Serial.println("ERROR: MPU no inicializo en 0x68 ni 0x69. Sample usa velocidad fija.");
  return false;
}

